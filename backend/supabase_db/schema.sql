-- ============================================================
-- Merry's Way Coffee Shop - Supabase schema (single source of truth)
-- ============================================================
-- FRESH INSTALL: run this whole file once in the Supabase SQL editor.
-- EXISTING PROJECT: run reset_schema.sql first. That DELETES ALL APP DATA
-- (profiles, orders, chat history, products). Auth users are kept.
--
-- After running it:
--   cd backend
--   uv run python scripts/seed_products.py     # menu + embeddings
--   uv run python scripts/index_metadata.py    # BI schema metadata
--   then make yourself admin (see the bottom of this file)
--
-- Conventions
--   user_email   : lowercase email is the user key everywhere
--   session_id   : UUID generated by the frontend
--   orders       : header in coffee_shop_orders, lines in coffee_shop_order_items
--   status       : 'pending' (live cart) | 'confirmed'; cancelled carts are deleted
--
-- Security model
--   * The backend uses the SERVICE ROLE key for all database access (the
--     frontend never talks to the database directly) and the service role
--     bypasses RLS. So NO table lets end users write; they can only read their
--     own rows if they ever call the REST API directly.
--   * Internal functions (cart, chat append, SQL runner, schema search) are
--     callable by the service role only.
-- ============================================================

create extension if not exists vector;


-- ── Helpers ───────────────────────────────────────────────────────────────────

create or replace function set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;


-- ── Profiles (preferences, allergies, admin flag) ─────────────────────────────

create table if not exists coffee_shop_profiles (
  user_email    text         primary key check (user_email = lower(user_email)),
  name          text,
  likes         jsonb        not null default '[]',
  dislikes      jsonb        not null default '[]',
  allergies     jsonb        not null default '[]',
  last_order    text,
  feedback      jsonb        not null default '[]',
  location      text,
  is_admin      boolean      not null default false,
  created_at    timestamptz  not null default now(),
  last_updated  timestamptz  not null default now()
