-- Schema metadata the BI agent searches to decide which tables/columns to use
-- (filled by scripts/index_metadata.py).
create table if not exists coffee_shop_schema_metadata (
  id         uuid         primary key default gen_random_uuid(),
  content    text         not null,
  metadata   jsonb        not null,
  embedding  vector(768)
);

alter table coffee_shop_schema_metadata enable row level security;

create or replace function match_schema_metadata(
  query_embedding  vector(768),
  match_threshold  float,
  match_count      int
)
returns table (
  id          uuid,
  content     text,
  metadata    jsonb,
  similarity  float
)
language sql
stable
as $$
  select m.id, m.content, m.metadata,
         1 - (m.embedding <=> query_embedding) as similarity
  from coffee_shop_schema_metadata m
  where 1 - (m.embedding <=> query_embedding) > match_threshold
  order by m.embedding <=> query_embedding
  limit match_count;
$$;

revoke all on function match_schema_metadata(vector, float, int) from public, anon, authenticated;
