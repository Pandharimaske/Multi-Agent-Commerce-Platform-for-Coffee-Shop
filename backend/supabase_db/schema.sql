-- Atomic append (no read-modify-write race). Creates the session if needed and
-- only ever appends to a session owned by the same user.
create or replace function append_chat_messages(
  p_session_id    uuid,
  p_user_email    text,
  p_new_messages  jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := lower(trim(p_user_email));
begin
  insert into coffee_shop_profiles (user_email) values (v_email)
  on conflict (user_email) do nothing;

  insert into coffee_shop_sessions (session_id, user_email, messages)
  values (p_session_id, v_email, coalesce(p_new_messages, '[]'::jsonb))
  on conflict (session_id) do update
    set messages    = coffee_shop_sessions.messages || coalesce(excluded.messages, '[]'::jsonb),
        last_active = now()
    where coffee_shop_sessions.user_email = v_email;
end;
$$;

revoke all on function append_chat_messages(uuid, text, jsonb) from public, anon, authenticated;
grant execute on function append_chat_messages(uuid, text, jsonb) to service_role;


