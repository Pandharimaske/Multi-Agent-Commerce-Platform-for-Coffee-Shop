-- Semantic menu search used by the RAG tools (src/rag/retriever.py).
create or replace function match_coffee_products(
  query_embedding  vector(768),
  match_threshold  float,
  match_count      int
)
returns table (
  id           uuid,
  name         text,
  category     text,
  description  text,
  price        float,
  rating       float,
  ingredients  jsonb,
  image_url    text,
  similarity   float
)
language sql
stable
as $$
  select p.id, p.name, p.category, p.description, p.price, p.rating,
         p.ingredients, p.image_url,
         1 - (p.embedding <=> query_embedding) as similarity
  from coffee_shop_products p
  where p.embedding is not null
    and 1 - (p.embedding <=> query_embedding) > match_threshold
  order by p.embedding <=> query_embedding
  limit match_count;
$$;


-- ── Orders: header + line items ───────────────────────────────────────────────

create table if not exists coffee_shop_orders (
  id            uuid           primary key default gen_random_uuid(),
  user_email    text           not null references coffee_shop_profiles(user_email) on delete cascade,
  status        text           not null default 'pending' check (status in ('pending', 'confirmed')),
  total         numeric(10,2)  not null default 0 check (total >= 0),
  created_at    timestamptz    not null default now(),
  confirmed_at  timestamptz,
  updated_at    timestamptz    not null default now(),
  check ((status = 'confirmed') = (confirmed_at is not null))
);

-- At most ONE pending cart per user.
create unique index if not exists coffee_shop_orders_one_pending_per_user
  on coffee_shop_orders (user_email) where status = 'pending';
create index if not exists coffee_shop_orders_user_status_idx
  on coffee_shop_orders (user_email, status);
create index if not exists coffee_shop_orders_status_confirmed_idx
  on coffee_shop_orders (status, confirmed_at);

drop trigger if exists coffee_shop_orders_set_updated_at on coffee_shop_orders;
create trigger coffee_shop_orders_set_updated_at
  before update on coffee_shop_orders
  for each row execute function set_updated_at();

alter table coffee_shop_orders enable row level security;

drop policy if exists "Users can read own orders" on coffee_shop_orders;
create policy "Users can read own orders"
  on coffee_shop_orders for select
  using (lower(auth.jwt() ->> 'email') = user_email);
-- No write policies: otherwise a user could mark their own order 'confirmed'
-- or change its total through the REST API without paying.


create table if not exists coffee_shop_order_items (
  id            uuid           primary key default gen_random_uuid(),
  order_id      uuid           not null references coffee_shop_orders(id) on delete cascade,
  product_id    uuid           references coffee_shop_products(id) on delete set null,
  product_name  text           not null,
  quantity      integer        not null check (quantity > 0),
  unit_price    numeric(10,2)  not null check (unit_price >= 0),   -- price at order time
  line_total    numeric(10,2)  not null check (line_total >= 0),
  image_url     text,
  line_no       integer        not null default 0,
  unique (order_id, product_id)
);

create index if not exists coffee_shop_order_items_order_idx
  on coffee_shop_order_items (order_id);
create index if not exists coffee_shop_order_items_product_idx
  on coffee_shop_order_items (product_id);

alter table coffee_shop_order_items enable row level security;

drop policy if exists "Users can read own order items" on coffee_shop_order_items;
create policy "Users can read own order items"
  on coffee_shop_order_items for select
  using (
    exists (
      select 1 from coffee_shop_orders o
      where o.id = coffee_shop_order_items.order_id
        and o.user_email = lower(auth.jwt() ->> 'email')
    )
  );


-- Atomically replace the user's pending cart. `p_items` is a JSON array of
-- {name, quantity}. Prices and images come from coffee_shop_products, so any
-- price a client sends is ignored. Returns the new order id, or NULL if the
-- cart ended up empty.
create or replace function replace_pending_order(p_user_email text, p_items jsonb)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email    text := lower(trim(p_user_email));
  v_order_id uuid;
  v_total    numeric(10,2);
begin
  perform pg_advisory_xact_lock(hashtext(v_email));

  insert into coffee_shop_profiles (user_email) values (v_email)
  on conflict (user_email) do nothing;

  delete from coffee_shop_orders
   where user_email = v_email and status = 'pending';

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    return null;
  end if;

  insert into coffee_shop_orders (user_email, status, total)
  values (v_email, 'pending', 0)
  returning id into v_order_id;

  insert into coffee_shop_order_items
         (order_id, product_id, product_name, quantity, unit_price, line_total, image_url, line_no)
  select v_order_id,
         p.id,
         p.name,
         sum(q.qty)::int,
         p.price::numeric(10,2),
         round(p.price::numeric * sum(q.qty), 2),
         p.image_url,
         min(q.ord)::int
  from (
         select lower(t.elem->>'name') as lname,
                coalesce((t.elem->>'quantity')::numeric, 0)::int as qty,
                t.ord
         from jsonb_array_elements(p_items) with ordinality as t(elem, ord)
       ) q
  join coffee_shop_products p on lower(p.name) = q.lname
  where q.qty > 0
  group by p.id, p.name, p.price, p.image_url;

  select coalesce(sum(line_total), 0) into v_total
    from coffee_shop_order_items where order_id = v_order_id;

  if v_total <= 0 then
    delete from coffee_shop_orders where id = v_order_id;
    return null;
  end if;

  update coffee_shop_orders set total = v_total where id = v_order_id;

  return v_order_id;
end;
$$;


-- Confirm the user's pending order. If `p_items` is given, the cart is first
-- re-synced from it (priced live). Every line is then re-priced from the live
-- product table, so the stored total is authoritative. Returns
-- {order_id, total, items:[{name, quantity, per_unit_price, total_price, image_url}]}
-- or NULL if there is nothing to confirm.
create or replace function confirm_pending_order(p_user_email text, p_items jsonb default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email    text := lower(trim(p_user_email));
  v_order_id uuid;
  v_total    numeric(10,2);
  v_items    jsonb;
begin
  perform pg_advisory_xact_lock(hashtext(v_email));

  if p_items is not null then
    perform replace_pending_order(v_email, p_items);
  end if;

  select id into v_order_id
    from coffee_shop_orders
   where user_email = v_email and status = 'pending'
   order by updated_at desc
   limit 1
   for update;

  if v_order_id is null then
    return null;
  end if;

  update coffee_shop_order_items i
     set unit_price = p.price::numeric(10,2),
         line_total = round(p.price::numeric * i.quantity, 2)
    from coffee_shop_products p
   where i.order_id = v_order_id
     and i.product_id = p.id;

  select coalesce(sum(line_total), 0) into v_total
    from coffee_shop_order_items where order_id = v_order_id;

  if v_total <= 0 then
    return null;
  end if;

  update coffee_shop_orders
     set status = 'confirmed',
         total = v_total,
         confirmed_at = now()
   where id = v_order_id;

  select coalesce(
           jsonb_agg(
             jsonb_build_object(
               'name', product_name,
               'quantity', quantity,
               'per_unit_price', unit_price,
               'total_price', line_total,
               'image_url', image_url
             ) order by line_no
           ),
           '[]'::jsonb)
    into v_items
    from coffee_shop_order_items
   where order_id = v_order_id;

  return jsonb_build_object('order_id', v_order_id, 'total', v_total, 'items', v_items);
end;
$$;

revoke all on function replace_pending_order(text, jsonb) from public, anon, authenticated;
grant execute on function replace_pending_order(text, jsonb) to service_role;

revoke all on function confirm_pending_order(text, jsonb) from public, anon, authenticated;
grant execute on function confirm_pending_order(text, jsonb) to service_role;


